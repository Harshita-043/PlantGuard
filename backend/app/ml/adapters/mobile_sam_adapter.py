"""MobileSAM ViT-T candidate generation using the official PyTorch package."""

import logging
import pickle
from pathlib import Path
from typing import Any, Dict, List, Optional

import numpy as np

from app.ml.adapters.sam_adapter import Sam2LeafSegmentationAdapter
from app.ml.errors import InferenceErrorCode
from app.ml.interfaces.adapter import (
    BaseModelAdapter,
    ContractSpec,
    EvaluationStatus,
    FailureBehavior,
    ModelLoadingStatus,
    PreprocessingSpec,
)

logger = logging.getLogger(__name__)


class MobileSamLeafSegmentationAdapter(BaseModelAdapter):
    """Generate automatic point-grid masks with the official MobileSAM predictor."""

    def __init__(
        self,
        artifact_path: Optional[Path] = None,
        artifact_version: str = "mobilesam-vit-t",
        points_per_side: int = 8,
        points_per_batch: int = 8,
        failure_behavior: FailureBehavior = FailureBehavior.FAIL_FAST,
    ):
        super().__init__(
            name="mobile_sam_instance_segmentation",
            artifact_path=artifact_path or self._resolve_default_path(),
            artifact_version=artifact_version,
            device_requirements="cpu_supported",
            failure_behavior=failure_behavior,
            evaluation_status=EvaluationStatus.EXPERIMENTAL,
        )
        if points_per_side < 1 or points_per_batch < 1:
            raise ValueError("MobileSAM point-grid sizes must be positive")
        self.points_per_side = points_per_side
        self.points_per_batch = points_per_batch
        self._model = None
        self._predictor = None
        self.last_generated_candidate_count = 0

    def get_input_contract(self) -> ContractSpec:
        return ContractSpec(
            data_type="np.ndarray[uint8]",
            shape=("H", "W", 3),
            description="Raw RGB uint8 image array",
        )

    def get_preprocessing_spec(self) -> PreprocessingSpec:
        return PreprocessingSpec(
            target_size=(1024, 1024),
            color_mode="RGB",
        )

    def get_output_contract(self) -> ContractSpec:
        return ContractSpec(
            data_type="List[Dict[str, Any]]",
            shape=("N",),
            description="Filtered candidate leaf masks generated by MobileSAM",
        )

    def get_class_mapping(self) -> Optional[Dict[int, str]]:
        return None

    @staticmethod
    def _resolve_default_path() -> Path:
        candidates = [
            Path("artifacts/mobilesam/mobile_sam.pt"),
            Path("../artifacts/mobilesam/mobile_sam.pt"),
        ]
        for candidate in candidates:
            if candidate.is_file():
                return candidate.resolve()
        return Path("artifacts/mobilesam/mobile_sam.pt")

    def load(self, target_device: str = "cpu") -> bool:
        self.loading_status = ModelLoadingStatus.LOADING
        self.active_device = target_device
        self.last_error = None
        self.load_error_code = None
        if not self.artifact_path.is_file():
            self.last_error = "MobileSAM checkpoint is missing"
            self.load_error_code = InferenceErrorCode.MISSING_ARTIFACT
            self.loading_status = ModelLoadingStatus.FAILED
            return False

        try:
            import torch
            from mobile_sam import SamPredictor, sam_model_registry

            if target_device.startswith("cuda") and not torch.cuda.is_available():
                self.last_error = "CUDA was requested but is unavailable"
                self.load_error_code = InferenceErrorCode.UNSUPPORTED_RUNTIME
                self.loading_status = ModelLoadingStatus.FAILED
                return False
            if target_device == "mps" and not (
                hasattr(torch.backends, "mps") and torch.backends.mps.is_available()
            ):
                self.last_error = "MPS was requested but is unavailable"
                self.load_error_code = InferenceErrorCode.UNSUPPORTED_RUNTIME
                self.loading_status = ModelLoadingStatus.FAILED
                return False
            if target_device not in {"cpu", "mps"} and not target_device.startswith("cuda"):
                self.last_error = f"Unsupported MobileSAM device: {target_device}"
                self.load_error_code = InferenceErrorCode.UNSUPPORTED_RUNTIME
                self.loading_status = ModelLoadingStatus.FAILED
                return False

            try:
                state_dict = torch.load(
                    str(self.artifact_path),
                    map_location="cpu",
                    weights_only=True,
                )
            except (EOFError, OSError, pickle.UnpicklingError, RuntimeError) as exc:
                self.last_error = f"MobileSAM checkpoint could not be safely deserialized: {type(exc).__name__}"
                self.load_error_code = InferenceErrorCode.ARTIFACT_INTEGRITY
                self.loading_status = ModelLoadingStatus.FAILED
                logger.warning("%s", self.last_error)
                return False

            model = sam_model_registry["vit_t"](checkpoint=None)
            self._validate_state_dict(model, state_dict, torch)
            model.load_state_dict(state_dict, strict=True)
            model.to(device=target_device).eval()
            self._model = model
            self._predictor = SamPredictor(model)
            self.loading_status = ModelLoadingStatus.READY
            logger.info("MobileSAM vit_t loaded on %s", target_device)
            return True
        except ImportError as exc:
            self.last_error = "MobileSAM PyTorch package is unavailable"
            self.load_error_code = InferenceErrorCode.UNSUPPORTED_RUNTIME
            logger.warning("%s: %s", self.last_error, type(exc).__name__)
        except (RuntimeError, TypeError, ValueError) as exc:
            self.last_error = f"MobileSAM checkpoint is incompatible with the ViT-T architecture: {exc}"
            self.load_error_code = InferenceErrorCode.MODEL_FAILURE
            logger.warning("%s", self.last_error)
        self.loading_status = ModelLoadingStatus.FAILED
        return False

    @staticmethod
    def _validate_state_dict(model: Any, state_dict: Any, torch: Any) -> None:
        if not isinstance(state_dict, dict) or any(
            not isinstance(key, str) or not torch.is_tensor(value)
            for key, value in state_dict.items()
        ):
            raise ValueError("expected a plain tensor state dictionary")

        model_state = model.state_dict()
        missing = sorted(model_state.keys() - state_dict.keys())
        unexpected = sorted(state_dict.keys() - model_state.keys())
        mismatched_shapes = sorted(
            key for key in model_state.keys() & state_dict.keys()
            if model_state[key].shape != state_dict[key].shape
        )
        if missing or unexpected or mismatched_shapes:
            raise ValueError(
                "state dictionary does not match ViT-T keys or tensor shapes "
                f"(missing={missing[:5]}, unexpected={unexpected[:5]}, "
                f"shape_mismatches={mismatched_shapes[:5]})"
            )

    def unload(self) -> None:
        self._predictor = None
        self._model = None
        self.loading_status = ModelLoadingStatus.UNLOADED
        self.active_device = None

    def predict(self, raw_rgb_image: np.ndarray) -> List[Dict[str, Any]]:
        if raw_rgb_image.ndim != 3 or raw_rgb_image.shape[2] != 3 or raw_rgb_image.dtype != np.uint8:
            raise ValueError("MobileSAM expects an RGB uint8 image with shape (H, W, 3)")
        if not self.is_ready() or self._predictor is None:
            from app.ml.errors import ModelCapabilityError
            raise ModelCapabilityError(
                InferenceErrorCode.UNSUPPORTED_RUNTIME,
                "MobileSAM is not loaded",
                stage="mobilesam",
            )

        import torch

        height, width = raw_rgb_image.shape[:2]
        self._predictor.set_image(raw_rgb_image)
        x_points = np.linspace(0.05, 0.95, self.points_per_side, dtype=np.float32) * width
        y_points = np.linspace(0.05, 0.95, self.points_per_side, dtype=np.float32) * height
        point_grid = np.stack(np.meshgrid(x_points, y_points), axis=-1).reshape(-1, 2)
        generated: list[dict[str, Any]] = []

        with torch.inference_mode():
            for start in range(0, len(point_grid), self.points_per_batch):
                points = torch.as_tensor(
                    point_grid[start:start + self.points_per_batch],
                    dtype=torch.float32,
                    device=self.active_device,
                ).unsqueeze(1)
                labels = torch.ones(
                    (points.shape[0], 1),
                    dtype=torch.int64,
                    device=self.active_device,
                )
                transformed = self._predictor.transform.apply_coords_torch(points, (height, width))
                masks, scores, _ = self._predictor.predict_torch(
                    point_coords=transformed,
                    point_labels=labels,
                    multimask_output=True,
                    return_logits=False,
                )
                best_indices = scores.argmax(dim=1)
                best_masks = masks[torch.arange(masks.shape[0], device=masks.device), best_indices]
                best_scores = scores[torch.arange(scores.shape[0], device=scores.device), best_indices]
                for mask, score in zip(best_masks, best_scores):
                    segmentation = mask.detach().cpu().numpy().astype(bool, copy=False)
                    if not np.any(segmentation):
                        continue
                    generated.append({
                        "segmentation": segmentation,
                        "area": int(np.count_nonzero(segmentation)),
                        "predicted_iou": float(score.detach().cpu()),
                    })

        candidates = Sam2LeafSegmentationAdapter._filter_and_rank_leaf_candidates(
            generated, raw_rgb_image.shape[:2]
        )
        self.last_generated_candidate_count = len(generated)
        for candidate in candidates:
            candidate["method"] = "mobilesam.point_grid_predictor"
        return candidates
